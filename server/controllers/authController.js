// REGISTER CONTROLLER
export const register = async (req, res, next) => {
    try {
        const { email, password, role, fullName, phone } = req.body;

        // 1. Check if user already exists
        const userCheck = await pool.query('SELECT id FROM users WHERE email = $1', [email]);
        if (userCheck.rows.length > 0) {
            return res.status(409).json({ status: 'error', message: 'User already exists' });
        }

        // 2. Hash Password
        const passwordHash = await bcrypt.hash(password, SALT_ROUNDS);

        // 3. Insert User (UUID is generated by DB default gen_random_uuid())
        // 3. Insert User (UUID is generated by DB default gen_random_uuid())
        const newUser = await pool.query(
            'INSERT INTO users (email, password_hash, role, full_name) VALUES ($1, $2, $3, $4) RETURNING id, email, role, full_name, created_at',
            [email, passwordHash, role, fullName]
        );

        const user = newUser.rows[0];

        // 4. Create Provider Profile Placeholder if role is provider
        if (role === 'provider') {
            const tempRut = `TEMP-${Date.now()}`; // Temporary RUT until KYC
            const providerName = fullName || `Provider ${user.email}`;
            // CODE-SIDE FIX: Insert placeholders for non-nullable columns to bypass DB migration issues
            await pool.query(
                `INSERT INTO provider_profiles 
                (user_id, full_name, rut, phone, is_verified, bio, coverage_area, coverage_communes) 
                VALUES ($1, $2, $3, $4, $5, $6, $7, $8::jsonb)`,
                [
                    user.id,
                    providerName,
                    tempRut,
                    phone || null,
                    false,
                    'Pendiente de configurar', // Placeholder for bio (NOT NULL)
                    'Pendiente',               // Placeholder for coverage_area (NOT NULL)
                    JSON.stringify([])
                ]
            );
        }

        // 5. Generate Token
        const token = jwt.sign(
            { id: user.id, role: user.role, email: user.email },
            JWT_SECRET,
            { expiresIn: JWT_EXPIRES_IN }
        );

        // 6. Response (Stateless - Token in body)
        res.status(201).json({
            status: 'success',
            message: 'User registered successfully',
            token,
            user: {
                id: user.id,
                email: user.email,
                role: user.role,
            },
        });

    } catch (err) {
        logger.error(`Register Error: ${err.message}`);
        await AlertService.notify(err, { component: 'Auth', action: 'Register', email: req.body.email }, SEVERITY.HIGH);
        next(err);
    }
};

// LOGIN CONTROLLER
export const login = async (req, res, next) => {
    try {
        const { email, password } = req.body;

        // 1. Find User
        const result = await pool.query('SELECT * FROM users WHERE email = $1', [email]);

        if (result.rows.length === 0) {
            return res.status(401).json({ status: 'error', message: 'Invalid credentials' });
        }

        const user = result.rows[0];

        if (user.is_blocked) {
            return res.status(403).json({ status: 'error', message: 'Cuenta bloqueada. Contacta a soporte.' });
        }

        // 2. Compare Password
        const isMatch = await bcrypt.compare(password, user.password_hash);
        if (!isMatch) {
            return res.status(401).json({ status: 'error', message: 'Invalid credentials' });
        }

        // 3. Generate Token
        const token = jwt.sign(
            { id: user.id, role: user.role, email: user.email },
            JWT_SECRET,
            { expiresIn: JWT_EXPIRES_IN }
        );

        // 3.5 Fetch Profile Info (if provider)
        let profileData = {};
        if (user.role === 'provider') {
            const profileRes = await pool.query('SELECT full_name, profile_image_url FROM provider_profiles WHERE user_id = $1', [user.id]);
            if (profileRes.rows.length > 0) {
                profileData = profileRes.rows[0];
            }
        }

        // 4. Response
        res.json({
            status: 'success',
            message: 'Login successful',
            token,
            user: {
                id: user.id,
                email: user.email,
                role: user.role,
                full_name: profileData.full_name || user.email,
                profile_image_url: profileData.profile_image_url
            },
        });

    } catch (err) {
        logger.error(`Login Error: ${err.message}`);
        next(err);
    }
};


