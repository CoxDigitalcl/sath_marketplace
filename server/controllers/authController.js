// POST /api/auth/forgot-password
// Generates a 6-digit code, hashes it, stores in DB, sends via email
export const requestPasswordReset = async (req, res, next) => {
    try {
        const { email } = req.body;

        // Always return success to prevent user enumeration
        const genericMessage = 'Si el correo está registrado en nuestra plataforma, recibirás un código de verificación en los próximos minutos.';

        // 1. Find user
        const result = await pool.query('SELECT id, email FROM users WHERE email = $1', [email.toLowerCase()]);
        
        if (result.rows.length === 0) {
            // Return same message to prevent enumeration
            logger.info(`[Password Reset] Requested for non-existent email: ${email}`);
            return res.json({ status: 'success', message: genericMessage });
        }

        const user = result.rows[0];

        // 2. Generate 6-digit code
        const code = crypto.randomInt(100000, 999999).toString();
        
        // 3. Hash the code before storing (security best practice)
        const hashedCode = await bcrypt.hash(code, SALT_ROUNDS);
        
        // 4. Store hashed code + expiry in DB
        const expires = new Date(Date.now() + RESET_CODE_EXPIRY_MINUTES * 60 * 1000);
        await pool.query(
            'UPDATE users SET reset_token = $1, reset_token_expires = $2, updated_at = NOW() WHERE id = $3',
            [hashedCode, expires, user.id]
        );

        // 5. Send email with rich template
        const emailHTML = buildResetCodeEmailHTML(code, user.email);
        const emailSent = await sendEmail({
            to: user.email,
            subject: `🔐 Código de verificación: ${code} — Recuperación de contraseña | Serviciosatuhogar`,
            html: emailHTML
        });

        if (!emailSent) {
            logger.error(`[Password Reset] Failed to send email to: ${user.email}`);
        } else {
            logger.info(`[Password Reset] Code sent to: ${user.email}`);
        }

        res.json({ status: 'success', message: genericMessage });

    } catch (err) {
        logger.error(`Password Reset Request Error: ${err.message}`);
        await AlertService.notify(err, { component: 'Auth', action: 'RequestPasswordReset' }, SEVERITY.MEDIUM);
        next(err);
    }
};

// POST /api/auth/verify-reset-code
// Validates the 6-digit code and returns a short-lived JWT for the reset step
export const verifyResetCode = async (req, res, next) => {
    try {
        const { email, code } = req.body;

        // 1. Find user with valid reset token
        const result = await pool.query(
            'SELECT id, reset_token, reset_token_expires FROM users WHERE email = $1',
            [email.toLowerCase()]
        );

        if (result.rows.length === 0) {
            return res.status(400).json({ 
                status: 'error', 
                message: 'Código inválido o expirado. Por favor, solicita un nuevo código.' 
            });
        }

        const user = result.rows[0];

        // 2. Check if token exists and hasn't expired
        if (!user.reset_token || !user.reset_token_expires) {
            return res.status(400).json({ 
                status: 'error', 
                message: 'No hay una solicitud de recuperación activa. Por favor, solicita un nuevo código.' 
            });
        }

        if (new Date() > new Date(user.reset_token_expires)) {
            // Clean up expired token
            await pool.query('UPDATE users SET reset_token = NULL, reset_token_expires = NULL WHERE id = $1', [user.id]);
            return res.status(400).json({ 
                status: 'error', 
                message: 'El código ha expirado. Por favor, solicita uno nuevo.' 
            });
        }

        // 3. Compare code with hashed version
        const isMatch = await bcrypt.compare(code, user.reset_token);
        if (!isMatch) {
            return res.status(400).json({ 
                status: 'error', 
                message: 'Código incorrecto. Verifica el código e intenta nuevamente.' 
            });
        }

        // 4. Code is valid! Generate a short-lived reset session token
        const resetSessionToken = jwt.sign(
            { id: user.id, purpose: 'password_reset' },
            JWT_SECRET,
            { expiresIn: RESET_SESSION_EXPIRY }
        );

        // 5. Clear the used code from DB
        await pool.query('UPDATE users SET reset_token = NULL, reset_token_expires = NULL WHERE id = $1', [user.id]);

        logger.info(`[Password Reset] Code verified for user: ${user.id}`);

        res.json({
            status: 'success',
            message: 'Código verificado correctamente. Ahora puedes crear tu nueva contraseña.',
            resetToken: resetSessionToken
        });

    } catch (err) {
        logger.error(`Verify Reset Code Error: ${err.message}`);
        next(err);
    }
};

// POST /api/auth/reset-password
// Consumes the reset session token and sets a new password
export const resetPassword = async (req, res, next) => {
    try {
        const { resetToken, newPassword } = req.body;

        // 1. Verify the reset session token
        let decoded;
        try {
            decoded = jwt.verify(resetToken, JWT_SECRET);
        } catch (jwtErr) {
            return res.status(400).json({ 
                status: 'error', 
                message: 'La sesión de recuperación ha expirado. Por favor, inicia el proceso nuevamente.' 
            });
        }

        // 2. Ensure the token is for password reset purpose
        if (decoded.purpose !== 'password_reset') {
            return res.status(400).json({ 
                status: 'error', 
                message: 'Token inválido para esta operación.' 
            });
        }

        // 3. Hash new password
        const passwordHash = await bcrypt.hash(newPassword, SALT_ROUNDS);

        // 4. Update password in DB
        await pool.query(
            'UPDATE users SET password_hash = $1, reset_token = NULL, reset_token_expires = NULL, updated_at = NOW() WHERE id = $2',
            [passwordHash, decoded.id]
        );

        logger.info(`[Password Reset] Password successfully reset for user: ${decoded.id}`);

        res.json({
            status: 'success',
            message: '¡Tu contraseña ha sido actualizada exitosamente! Ya puedes iniciar sesión con tu nueva contraseña.'
        });

    } catch (err) {
        logger.error(`Reset Password Error: ${err.message}`);
        next(err);
    }
};

// POST /api/auth/change-password
// For authenticated users wanting to change their password from the dashboard
export const changePassword = async (req, res, next) => {
    try {
        const userId = req.user.id; // From auth middleware
        const { currentPassword, newPassword } = req.body;

        // 1. Fetch current password hash
        const result = await pool.query('SELECT password_hash FROM users WHERE id = $1', [userId]);
        if (result.rows.length === 0) {
            return res.status(404).json({ status: 'error', message: 'Usuario no encontrado.' });
        }

        // 2. Verify current password
        const isMatch = await bcrypt.compare(currentPassword, result.rows[0].password_hash);
        if (!isMatch) {
            return res.status(401).json({ 
                status: 'error', 
                message: 'La contraseña actual es incorrecta.' 
            });
        }

        // 3. Prevent same password
        const isSame = await bcrypt.compare(newPassword, result.rows[0].password_hash);
        if (isSame) {
            return res.status(400).json({ 
                status: 'error', 
                message: 'La nueva contraseña debe ser diferente a la actual.' 
            });
        }

        // 4. Hash and update
        const passwordHash = await bcrypt.hash(newPassword, SALT_ROUNDS);
        await pool.query(
            'UPDATE users SET password_hash = $1, updated_at = NOW() WHERE id = $2',
            [passwordHash, userId]
        );

        logger.info(`[Password Change] Password changed for user: ${userId}`);

        res.json({
            status: 'success',
            message: 'Tu contraseña ha sido actualizada exitosamente.'
        });

    } catch (err) {
        logger.error(`Change Password Error: ${err.message}`);
        next(err);
    }
};
